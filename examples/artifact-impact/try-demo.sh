#!/bin/sh
# Runs only the four named synthetic comparisons/replays. No installer/network.
set -eu
umask 077

work=
calls=0
finished=false
fail() {
    printf '{"schema":"policy-impact-kit-demo/v1","status":"error","code":"%s","work_directory":"%s","product_calls":%s,"simulation":true}\n' "$1" "$work" "$calls"
    exit 2
}
on_exit() {
    result=$?
    if [ "$finished" != true ] && [ "$result" -ne 0 ] && [ -n "$work" ]; then
        printf '%s\n' 'Demo stopped; private reports and diagnostics were retained.' >&2
        printf '%s\n' "$work" >&2
    fi
}
trap on_exit 0
trap 'fail INTERRUPTED' 1 2 15

case $# in
    0) ;;
    1) case $1 in
        --help|-h) printf '%s\n' 'Usage: ./try-demo.sh' 'Verify this extracted kit, then run two synthetic policy comparisons and two historical replays.' 'Uses standard shell/tools, a fresh private /tmp directory, and no Go/compiler/Python/network.' 'Retains private diagnostics/reports. Historical consistency is not a current execution grant.'; exit 0 ;;
        *) fail USAGE_INVALID ;;
       esac ;;
    *) fail USAGE_INVALID ;;
esac

kit=$(CDPATH= cd -P "$(dirname "$0")" && pwd -P) || fail KIT_DIRECTORY_INVALID
system=$(uname -s) || fail PLATFORM_UNAVAILABLE
machine=$(uname -m) || fail PLATFORM_UNAVAILABLE
case "$system/$machine" in
    Darwin/arm64) host=darwin/arm64 ;;
    Linux/x86_64) host=linux/amd64 ;;
    *) fail PLATFORM_UNSUPPORTED ;;
esac
[ -f "$kit/target.txt" ] && [ ! -L "$kit/target.txt" ] || fail TARGET_INVALID
target=$(cat "$kit/target.txt") || fail TARGET_INVALID
[ "$target" = "$host" ] || fail PLATFORM_MISMATCH

# Do not feed arbitrary paths in a changed checksum list to checksum tools.
# Names generated by the packager are relative and use this restricted alphabet.
[ -f "$kit/SHA256SUMS" ] && [ ! -L "$kit/SHA256SUMS" ] || fail CHECKSUM_LIST_INVALID
awk '
BEGIN { n=0; bad=0 }
{
  h=substr($0,1,64); sep=substr($0,65,2); p=substr($0,67);
  if (length(h)!=64 || h !~ /^[0-9a-f]+$/ || sep!="  " || p !~ /^[A-Za-z0-9._\/-]+$/ || p ~ /^\// || p ~ /(^|\/)\.\.?($|\/)/ || p ~ /\/\// || p=="SHA256SUMS" || seen[p]++) bad=1;
  n++;
}
END { if (n<16 || n>4096 || bad) exit 1 }
' "$kit/SHA256SUMS" || fail CHECKSUM_LIST_INVALID
for required in bin/policy-impact try-demo.sh target.txt buildinfo.txt manifest.json \
    seeds/case.json seeds/artifact.json seeds/policy-internal.json seeds/policy-external.json \
    notices/LICENSE notices/Go-LICENSE notices/LICENSE-REA notices/NOTICE.md \
    docs/policy-impact-first-use.md docs/artifact-policy-impact.md docs/artifact-policy-replay.md
do
    awk -v p="$required" 'substr($0,67)==p {found++} END {if(found!=1) exit 1}' "$kit/SHA256SUMS" || fail CHECKSUM_LIST_INVALID
done
# Reject static FIFO/symlink substitutions before any checksum tool reads them.
# This is a preflight over this extraction, not an atomic race-proof installer.
while IFS= read -r line; do
    relative=${line#*  }
    current=$kit
    remaining=$relative
    while :; do
        component=${remaining%%/*}
        current=$current/$component
        [ ! -L "$current" ] || fail CHECKSUM_MEMBER_INVALID
        if [ "$component" = "$remaining" ]; then
            [ -f "$current" ] || fail CHECKSUM_MEMBER_INVALID
            break
        fi
        [ -d "$current" ] || fail CHECKSUM_MEMBER_INVALID
        remaining=${remaining#*/}
    done
done < "$kit/SHA256SUMS"
if command -v sha256sum >/dev/null 2>&1; then
    hash_kind=sha256sum
    (CDPATH= cd -P "$kit" && sha256sum -c SHA256SUMS >/dev/null 2>&1) || fail CHECKSUM_MISMATCH
elif command -v shasum >/dev/null 2>&1; then
    hash_kind=shasum
    (CDPATH= cd -P "$kit" && shasum -a 256 -c SHA256SUMS >/dev/null 2>&1) || fail CHECKSUM_MISMATCH
else
    fail CHECKSUM_TOOL_MISSING
fi

hash_file() {
    if [ "$hash_kind" = sha256sum ]; then sha256sum "$1"; else shasum -a 256 "$1"; fi | awk '{print $1}'
}
[ -f "$kit/bin/policy-impact" ] && [ ! -L "$kit/bin/policy-impact" ] && [ -x "$kit/bin/policy-impact" ] || fail BINARY_INVALID
work=$(mktemp -d /tmp/gooo-policy-impact.XXXXXXXX) || fail PRIVATE_DIRECTORY_FAILED
chmod 700 "$work" || fail PRIVATE_DIRECTORY_FAILED
work=$(CDPATH= cd -P "$work" && pwd -P) || fail PRIVATE_DIRECTORY_FAILED
# Generated paths need no JSON escaping. No caller-selected directory is used.
case "$work" in
    /tmp/gooo-policy-impact.*|/private/tmp/gooo-policy-impact.*) ;;
    *) fail PRIVATE_DIRECTORY_INVALID ;;
esac
case "$work" in *[!A-Za-z0-9._/-]*) fail PRIVATE_DIRECTORY_INVALID ;; esac

digest_record() {
    digest=$(hash_file "$2") || fail DIGEST_FAILED
    [ ${#digest} -eq 64 ] || fail DIGEST_FAILED
    printf '%s\t%s\n' "$1" "$digest" >> "$work/digests.tsv"
}
digest_record binary_before "$kit/bin/policy-impact"
for name in case.json artifact.json policy-internal.json policy-external.json; do
    cp "$kit/seeds/$name" "$work/$name" || fail PRIVATE_INPUT_FAILED
    chmod 600 "$work/$name" || fail PRIVATE_INPUT_FAILED
done
placeholder=/replace-with-your-private-directory/artifact.json
count=$(awk -v p="$placeholder" 'index($0,p)>0 {n++} END {print n+0}' "$work/case.json") || fail CASE_TEMPLATE_INVALID
[ "$count" -eq 1 ] || fail CASE_TEMPLATE_INVALID
sed "s|$placeholder|$work/artifact.json|" "$work/case.json" > "$work/case.updated.json" || fail CASE_TEMPLATE_INVALID
mv "$work/case.updated.json" "$work/case.json" || fail CASE_TEMPLATE_INVALID
chmod 600 "$work/case.json" || fail PRIVATE_INPUT_FAILED
for name in case.json artifact.json policy-internal.json policy-external.json; do digest_record "input_$name" "$work/$name"; done

invoke() {
    index=$1; action=$2; direction=$3; name=$4
    shift 4
    calls=$((calls + 1))
    printf '%s\t%s\t%s\tstarted\t-\n' "$index" "$action" "$direction" >> "$work/product-calls.tsv"
    if "$kit/bin/policy-impact" "$@" > "$work/$name.summary.json" 2> "$work/$name.stderr"; then rc=0; else rc=$?; fi
    printf '%s\t%s\t%s\tcompleted\t%s\n' "$index" "$action" "$direction" "$rc" >> "$work/product-calls.tsv"
    digest_record "$name.summary" "$work/$name.summary.json"
    [ "$rc" -eq 0 ] || fail PRODUCT_CALL_FAILED
}
invoke 1 compare newly_denied 01-compare-denied compare \
    --case "$work/case.json" --before "$work/policy-internal.json" --after "$work/policy-external.json" --report "$work/01-compare-denied.report.json"
invoke 2 compare newly_allowed 02-compare-allowed compare \
    --case "$work/case.json" --before "$work/policy-external.json" --after "$work/policy-internal.json" --report "$work/02-compare-allowed.report.json"
digest_record denied_report_before_replay "$work/01-compare-denied.report.json"
digest_record allowed_report_before_replay "$work/02-compare-allowed.report.json"

# Delete only this script's four copies, preserving the reports and kit seeds.
for name in case.json artifact.json policy-internal.json policy-external.json; do
    rm "$work/$name" || fail INPUT_DELETE_FAILED
    [ ! -e "$work/$name" ] && [ ! -L "$work/$name" ] || fail INPUT_DELETE_FAILED
    printf '%s\n' "$name" >> "$work/inputs.deleted"
done
invoke 3 replay newly_denied 03-replay-denied replay --report "$work/01-compare-denied.report.json"
invoke 4 replay newly_allowed 04-replay-allowed replay --report "$work/02-compare-allowed.report.json"
digest_record denied_report_after_replay "$work/01-compare-denied.report.json"
digest_record allowed_report_after_replay "$work/02-compare-allowed.report.json"
digest_record binary_after "$kit/bin/policy-impact"
finished=true
printf '{"schema":"policy-impact-kit-demo/v1","status":"completed","work_directory":"%s","product_calls":4,"simulation":true}\n' "$work"
